using Dictora.Modules.Lessons.Infrastructure.YouTube;

namespace Dictora.Modules.Lessons.Tests;

/// <summary>
/// Runs the real adapter (YoutubeExplode parsing, track choice, cue mapping) against recorded
/// responses of short CC BY videos. See Fixtures/YouTube/README.md for attribution and re-recording.
/// </summary>
public class YoutubeExplodeReplayTests
{
    private static Task<CaptionFetchResult> FetchAsync(string videoId)
    {
        var source = new YoutubeExplodeCaptionSource(new HttpClient(new ReplayHttpHandler(videoId)));
        return source.FetchEnglishCaptionsAsync(videoId, CancellationToken.None);
    }

    [Fact]
    public async Task Picks_manual_en_over_auto_en_and_other_languages()
    {
        // gmoDpj1jtyA: zh-CN, manual en, auto en.
        var found = Assert.IsType<CaptionFetchResult.Found>(await FetchAsync("gmoDpj1jtyA"));

        Assert.Equal("en", found.LanguageCode);
        Assert.False(found.IsAutoGenerated);
        Assert.Equal(21, found.Cues.Count);
        Assert.StartsWith("Modern organizations face", found.Cues[0].Text);
    }

    [Fact]
    public async Task Picks_manual_regional_english_over_auto_en()
    {
        // Gj26fmXCn9U: auto en, manual en-US.
        var found = Assert.IsType<CaptionFetchResult.Found>(await FetchAsync("Gj26fmXCn9U"));

        Assert.Equal("en-US", found.LanguageCode);
        Assert.False(found.IsAutoGenerated);
        Assert.Equal(14, found.Cues.Count);
    }

    [Fact]
    public async Task Accepts_auto_generated_english_when_it_is_the_only_track()
    {
        // eklX9_LPkI0: auto en only.
        var found = Assert.IsType<CaptionFetchResult.Found>(await FetchAsync("eklX9_LPkI0"));

        Assert.Equal("en", found.LanguageCode);
        Assert.True(found.IsAutoGenerated);
        // The track has 23 cues, 11 of them empty spacers between lines, which are dropped.
        Assert.Equal(12, found.Cues.Count);
        Assert.Equal("how are you doing i'm fine how about", found.Cues[1].Text);
    }

    [Fact]
    public async Task Cues_are_ordered_trimmed_and_timed()
    {
        var found = Assert.IsType<CaptionFetchResult.Found>(await FetchAsync("gmoDpj1jtyA"));

        Assert.All(found.Cues, c =>
        {
            Assert.Equal(c.Text.Trim(), c.Text);
            Assert.NotEmpty(c.Text);
            Assert.True(c.Duration > TimeSpan.Zero);
        });
        Assert.Equal(found.Cues.OrderBy(c => c.Start), found.Cues);
        Assert.Equal(TimeSpan.FromMilliseconds(1079), found.Cues[0].Start);
        Assert.Equal(TimeSpan.FromMilliseconds(5851), found.Cues[0].Duration);
    }

    [Fact]
    public async Task Reports_no_english_captions_for_a_video_without_captions()
    {
        // 65iWtWqWmgY: no caption tracks at all.
        Assert.IsType<CaptionFetchResult.NoEnglishCaptions>(await FetchAsync("65iWtWqWmgY"));
    }
}
