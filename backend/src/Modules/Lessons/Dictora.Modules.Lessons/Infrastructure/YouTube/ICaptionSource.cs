namespace Dictora.Modules.Lessons.Infrastructure.YouTube;

/// <summary>
/// Step 2 of an import (ADR-002): the English caption track of a video that passed the licence check.
/// Adapters pick the track (manual <c>en</c>, manual <c>en-*</c>, auto <c>en</c>, auto <c>en-*</c>).
/// </summary>
internal interface ICaptionSource
{
    Task<CaptionFetchResult> FetchEnglishCaptionsAsync(string videoId, CancellationToken ct);
}
internal sealed record FetchedCue(string Text, TimeSpan Start, TimeSpan Duration);

internal abstract record CaptionFetchResult
{
    internal sealed record Found(string LanguageCode, bool IsAutoGenerated, IReadOnlyList<FetchedCue> Cues) : CaptionFetchResult;

    internal sealed record NoEnglishCaptions : CaptionFetchResult;

    internal sealed record VideoUnavailable : CaptionFetchResult;

    /// <summary>Blocked or rate-limited by YouTube (bot check, 429). Not the user's fault; alert on it.</summary>
    internal sealed record Blocked(string Reason) : CaptionFetchResult;

    /// <summary>Any other error (HTTP, parsing). Not the user's fault.</summary>
    internal sealed record Failed(string Reason) : CaptionFetchResult;
}

