using YoutubeExplode;
using YoutubeExplode.Exceptions;

namespace Dictora.Modules.Lessons.Infrastructure.YouTube;

/// <summary>
/// <see cref="ICaptionSource"/> backed by YoutubeExplode (ADR-002). This is the only file that may
/// use the package (enforced by <c>Dictora.ArchitectureTests</c>); everything is mapped to our own types.
/// </summary>
internal sealed class YoutubeExplodeCaptionSource(HttpClient http) : ICaptionSource
{
    /// <summary>Name of the typed <see cref="HttpClient"/>. The forward proxy (#25) is configured on it.</summary>
    internal const string HttpClientName = "YouTubeCaptions";

    // YoutubeClient wraps the HttpClient with its own handler (consent cookies, headers), so use it
    // rather than constructing ClosedCaptionClient directly.
    private readonly YoutubeClient _youtube = new(http);

    public async Task<CaptionFetchResult> FetchEnglishCaptionsAsync(string videoId, CancellationToken ct)
    {
        try
        {
            var manifest = await _youtube.Videos.ClosedCaptions.GetManifestAsync(videoId, ct);
            var index = CaptionTrackPicker.PickEnglish(
                manifest.Tracks.Select(t => new CaptionTrackCandidate(t.Language.Code, t.IsAutoGenerated)).ToList());
            if (index < 0)
            {
                return new CaptionFetchResult.NoEnglishCaptions();
            }

            var trackInfo = manifest.Tracks[index];
            var track = await _youtube.Videos.ClosedCaptions.GetAsync(trackInfo, ct);
            var cues = track.Captions
                .Where(c => !string.IsNullOrWhiteSpace(c.Text))
                .Select(c => new FetchedCue(c.Text.Trim(), c.Offset, c.Duration))
                .ToList();

            return cues.Count == 0
                ? new CaptionFetchResult.NoEnglishCaptions()
                : new CaptionFetchResult.Found(trackInfo.Language.Code, trackInfo.IsAutoGenerated, cues);
        }
        catch (Exception e) when (e is not OperationCanceledException)
        {
            return MapFailure(e);
        }
    }

    internal static CaptionFetchResult MapFailure(Exception e) => e switch
    {
        RequestLimitExceededException => new CaptionFetchResult.Blocked(e.Message),
        // Also covers VideoUnavailableException and VideoRequiresPurchaseException (subclasses).
        VideoUnplayableException => new CaptionFetchResult.VideoUnavailable(),
        _ => new CaptionFetchResult.Failed($"{e.GetType().Name}: {e.Message}"),
    };
}
